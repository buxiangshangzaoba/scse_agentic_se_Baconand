import json
from ollama import chat

## System prompt for the Planner Agent
## Describe its role, the expected output format, and the rules it must follow when generating a navigation plan.
## These are fairly similar to the Analyst Agent, but with a focus on creating a plan based on the requirements provided by the Analyst Agent.
SYSTEM_PROMPT = """
You are a planner agent for a mobile robot navigation system.
You will receive software requirements from the Analyst Agent.
Your job is to create a navigation plan based on these requirements.

Rules:
- The plan must include a strategy for robot navigation.
- The plan must include a list of decisions the robot can take during navigation.
- The plan must include the point at which the robot must stop.
- All actions must be one of: FORWARD, LEFT, RIGHT, STOP.

Output ONLY valid JSON with exactly this structure, no markdown, no explanation:
{
  "strategy": "string",
  "decisions": ["string", "string", "string"],
  "stop_condition": "string"
}
"""

## Function to validate the plan generated by the Planner Agent
## It should first check that the parameter it receives is of the correct type. 
# Then, it should validate all the keys and values contained in the above Python data structure of the input parameter.
def validate_plan(data):
    if not isinstance(data, dict):
        return False

    required_keys = {"strategy", "decisions", "stop_condition"}
    if set(data.keys()) != required_keys:
        return False

    if not isinstance(data["strategy"], str):
        return False

    if not isinstance(data["decisions"], list):
        return False

    for d in data["decisions"]:
        if not isinstance(d, str):
            return False

    if not isinstance(data["stop_condition"], str):
        return False

    return True


## Function to run the Planner Agent
## It takes the requirements generated by the Analyst Agent as input, sends them to the Planner Agent. Just like you did with the Analyst Agent.
## Take the response from the Planner Agent (Qwen), parse it and validate it using the validate_plan function, and return the validated plan.
def run_planner(requirement):
    last_error = None
    for attempt in range(1, 4):
        print(f"Planner agent: attempt {attempt}/3 ...")

        response = chat(
            model="qwen3:8b",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": json.dumps(requirement)}
            ]
        )

        raw_text = response.message.content.strip()

        if raw_text.startswith("```"):
            raw_text = raw_text.strip("`")
            if raw_text.lower().startswith("json"):
                raw_text = raw_text[4:]
            raw_text = raw_text.strip()

        try:
            parsed = json.loads(raw_text)
        except json.JSONDecodeError as e:
            last_error = e
            print(f"  -> JSON parse failed: {e}")
            continue

        if not validate_plan(parsed):
            last_error = ValueError("Plan failed validation")
            print("  -> validation failed, retrying ...")
            continue

        return parsed

    raise ValueError(f"Planner output failed after retries. Last error: {last_error}")
